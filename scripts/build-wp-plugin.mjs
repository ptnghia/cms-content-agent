// Package the WordPress plugin:
//   npm run build:wp                      -> dist/content-agent-<version>.zip (and dist/content-agent.zip)
//
// Branded build (display name + hosted "Connect" service baked in through brand.php):
//   BRAND_NAME="My Agent" BRAND_SERVICE_URL=https://service.example.com BRAND_ZIP=my-agent npm run build:wp
//   LIFETECH_BRAND=1 npm run build:wp     -> preset from scripts/brands/lifetech.json
// The plugin folder stays "content-agent", so a branded build updates the same plugin and settings.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, rmSync, copyFileSync, cpSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'wordpress');
const mainFile = path.join(src, 'content-agent', 'content-agent.php');
const version = /Version:\s*([\d.]+)/.exec(readFileSync(mainFile, 'utf8'))[1];
const dist = path.join(root, 'dist');
mkdirSync(dist, { recursive: true });

export function loadBrand(env) {
  const preset = env.LIFETECH_BRAND === '1'
    ? JSON.parse(readFileSync(path.join(root, 'scripts/brands/lifetech.json'), 'utf8'))
    : {};
  const brand = {
    name: env.BRAND_NAME || preset.name || '',
    serviceUrl: env.BRAND_SERVICE_URL || preset.serviceUrl || '',
    zip: env.BRAND_ZIP || preset.zip || '',
    description: env.BRAND_DESCRIPTION || preset.description || '',
  };
  if (!brand.name && !brand.serviceUrl && !brand.zip) return null;
  if (!brand.name || !brand.serviceUrl || !brand.zip) throw new Error('A branded build needs BRAND_NAME, BRAND_SERVICE_URL and BRAND_ZIP');
  const u = new URL(brand.serviceUrl);
  if (u.protocol !== 'https:' && !['localhost', '127.0.0.1'].includes(u.hostname)) throw new Error('BRAND_SERVICE_URL must be https');
  if (!/^[a-z0-9-]{1,60}$/.test(brand.zip)) throw new Error('BRAND_ZIP: lowercase letters, digits and -');
  if (/[\r\n*]/.test(brand.name + brand.description)) throw new Error('BRAND_NAME / BRAND_DESCRIPTION: one line, no "*"');
  return { ...brand, serviceUrl: brand.serviceUrl.replace(/\/+$/, '') };
}

/** PHP single-quoted string literal. */
const phpString = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function zip(cwd, out) {
  rmSync(out, { force: true });
  execFileSync('zip', ['-rq', '-X', out, 'content-agent', '-x', '*.DS_Store'], { cwd, stdio: 'inherit' });
}

const brand = loadBrand(process.env);
if (!brand) {
  const out = path.join(dist, `content-agent-${version}.zip`);
  zip(src, out);
  copyFileSync(out, path.join(dist, 'content-agent.zip'));
  console.log(`built ${path.relative(root, out)}`);
} else {
  const stage = path.join(dist, '.stage');
  rmSync(stage, { recursive: true, force: true });
  cpSync(path.join(src, 'content-agent'), path.join(stage, 'content-agent'), { recursive: true });
  writeFileSync(
    path.join(stage, 'content-agent', 'brand.php'),
    "<?php\n// Generated by scripts/build-wp-plugin.mjs for a branded build. Do not edit.\ndefined( 'ABSPATH' ) || exit;\n" +
      `define( 'CONTENT_AGENT_BRAND_NAME', ${phpString(brand.name)} );\n` +
      `define( 'CONTENT_AGENT_SERVICE_URL', ${phpString(brand.serviceUrl)} );\n`,
  );
  const stagedMain = path.join(stage, 'content-agent', 'content-agent.php');
  // Replacement functions: "$&" or "$1" in a brand name must stay literal.
  let header = readFileSync(stagedMain, 'utf8').replace(/^( \* Plugin Name:\s*).*$/m, (_, p) => p + brand.name);
  if (brand.description) header = header.replace(/^( \* Description:\s*).*$/m, (_, p) => p + brand.description);
  writeFileSync(stagedMain, header);
  const out = path.join(dist, `${brand.zip}-${version}.zip`);
  zip(stage, out);
  copyFileSync(out, path.join(dist, `${brand.zip}.zip`));
  rmSync(stage, { recursive: true, force: true });
  console.log(`built ${path.relative(root, out)} (${brand.name} -> ${brand.serviceUrl})`);
}
